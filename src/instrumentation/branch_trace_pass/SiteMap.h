// Таблица сайтов сравнений — побочный файл сборки цели (ADR 0047
// §Решение-5, вариант В3 разведки docs/experiments/adr-0047-dispatch-recon).
//
// Зачем. Запись сравнения несёт только номер сайта; чем этот номер является
// в исходнике, не знает никто. Таблица связывает номер с местом в коде
// (файл:строка:колонка, функция) по DebugLoc, поэтому она требует сборки
// цели с -g. Без -g строки заполняются прочерками, а сама таблица остаётся
// валидной: номера и модуль известны всегда.
//
// Чего таблица НЕ делает. Она не меняет инструментацию, не участвует в
// рантайме и не входит в IPC. Она не решает и вопрос уникальности номера:
// site_id нумеруется заново в каждом модуле, поэтому ключ здесь — ПАРА
// (модуль, site_id). Как быть с этим на стороне записи рантайма (соль модуля
// в номере либо новое поле) — решение ADR, и здесь оно не принимается.
#pragma once

#include <cstdint>
#include <vector>

namespace llvm {
class ICmpInst;
class Module;
}  // namespace llvm

namespace mlfuzzz3::sitemap {

// Одна строка таблицы: номер, присвоенный проходом, и сравнение, которому он
// принадлежит. Указатель живёт ровно столько, сколько модуль в проходе.
struct Row {
    std::uint32_t site_id = 0;
    const llvm::ICmpInst* cmp = nullptr;
};

// Пишет таблицу модуля в каталог из MLFUZZZ3_SITEMAP_DIR. Если переменная не
// задана, пуста или строк нет — не делает ничего: поведение прохода без неё
// в точности прежнее. Ошибки записи проглатываются намеренно: побочный файл
// не имеет права уронить сборку цели.
void WriteIfRequested(const llvm::Module& module, const std::vector<Row>& rows);

}  // namespace mlfuzzz3::sitemap
