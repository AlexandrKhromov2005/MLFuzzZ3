#!/usr/bin/env python3
"""Генератор детерминированной цели для эксперимента instrumentation-cost.

Порождает ОДИН самодостаточный C-файл с заданным числом ветвлений. Зерно
фиксировано аргументом --seed, генератор не читает ни времени, ни окружения,
ни файловой системы, поэтому вывод побайтово одинаков при одинаковых
аргументах. Число базовых блоков в LLVM IR считается отдельно (run.sh), здесь
задаётся только число порождённых ветвлений: --funcs * --branches.

Использование:
    python3 gen_target.py --seed 20260908 --funcs 40 --branches 25 -o target.c
"""
import argparse
import hashlib
import random
import sys

CMPS = ["==", "!=", "<", ">", "<=", ">="]
OPS = ["+=", "-=", "^="]


def generate(seed, funcs, branches):
    rnd = random.Random(seed)
    L = []
    L.append("/* AUTO-GENERATED by gen_target.py -- do not edit by hand. */")
    L.append("/* seed=%d funcs=%d branches_per_func=%d */" % (seed, funcs, branches))
    L.append("#include <stddef.h>")
    L.append("#include <stdint.h>")
    L.append("#include <stdio.h>")
    L.append("#include <string.h>")
    L.append("")
    for f in range(funcs):
        L.append("static uint32_t check_%d(const uint8_t *d, size_t n) {" % f)
        L.append("  uint32_t h = %du;" % rnd.randrange(1, 1 << 31))
        L.append("  if (n < %d) return h;" % (branches + 4))
        for b in range(branches):
            idx = rnd.randrange(0, branches + 4)
            cmp_ = rnd.choice(CMPS)
            val = rnd.randrange(0, 256)
            op_t = rnd.choice(OPS)
            op_f = rnd.choice(OPS)
            k_t = rnd.randrange(1, 1 << 20)
            k_f = rnd.randrange(1, 1 << 20)
            L.append("  if (d[%d] %s %du) {" % (idx, cmp_, val))
            L.append("    h %s %du;" % (op_t, k_t))
            L.append("  } else {")
            L.append("    h %s %du;" % (op_f, k_f))
            L.append("  }")
        L.append("  return h;")
        L.append("}")
        L.append("")
    L.append("uint32_t mlfuzzz3_target(const uint8_t *d, size_t n) {")
    L.append("  uint32_t acc = 0u;")
    for f in range(funcs):
        L.append("  acc ^= check_%d(d, n);" % f)
    L.append("  return acc;")
    L.append("}")
    L.append("")
    L.append("int main(int argc, char **argv) {")
    L.append("  uint8_t buf[4096];")
    L.append("  size_t n = 0;")
    L.append("  (void)argc;")
    L.append("  (void)argv;")
    L.append("  n = fread(buf, 1, sizeof(buf), stdin);")
    L.append("  return (int)(mlfuzzz3_target(buf, n) & 0x7fu);")
    L.append("}")
    return "\n".join(L) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seed", type=int, required=True)
    ap.add_argument("--funcs", type=int, default=40)
    ap.add_argument("--branches", type=int, default=25)
    ap.add_argument("-o", "--out", required=True)
    a = ap.parse_args()
    text = generate(a.seed, a.funcs, a.branches)
    with open(a.out, "w") as fh:
        fh.write(text)
    md5 = hashlib.md5(text.encode()).hexdigest()
    sys.stdout.write(
        "gen_target: seed=%d funcs=%d branches_per_func=%d branches_total=%d bytes=%d md5=%s\n"
        % (a.seed, a.funcs, a.branches, a.funcs * a.branches, len(text), md5)
    )


if __name__ == "__main__":
    main()
